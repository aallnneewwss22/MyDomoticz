"""Independent, short-lived authentication for settings-backup recovery.

The recovery key is generated by an already authenticated administrator and is
shown only once. Only a salted scrypt verifier is persisted; recovery sessions
exist in memory and grant read-only access to settings backups.
"""
from __future__ import annotations

import hashlib
import hmac
import json
import os
import re
import secrets
import tempfile
import threading
import time
from pathlib import Path
from typing import Callable


KEY_PATTERN = re.compile(r"^[A-Za-z0-9_-]{43}$")
SESSION_TTL_SECONDS = 300
RATE_WINDOW_SECONDS = 300
MAX_FAILED_ATTEMPTS = 5
SCRYPT_N = 1 << 14
SCRYPT_R = 8
SCRYPT_P = 1
SCRYPT_LENGTH = 32


class RecoveryUnauthorized(Exception):
    """The recovery key or session is absent or invalid."""


class RecoveryRateLimited(Exception):
    """Too many invalid recovery-key attempts from one client."""


class RecoveryAuth:
    def __init__(
        self,
        key_file: Path | str,
        *,
        clock: Callable[[], float] = time.monotonic,
        session_ttl: int = SESSION_TTL_SECONDS,
        rate_window: int = RATE_WINDOW_SECONDS,
        max_failed_attempts: int = MAX_FAILED_ATTEMPTS,
    ) -> None:
        self.key_file = Path(key_file)
        self.clock = clock
        self.session_ttl = session_ttl
        self.rate_window = rate_window
        self.max_failed_attempts = max_failed_attempts
        self._lock = threading.RLock()
        self._sessions: dict[str, float] = {}
        self._failures: dict[str, list[float]] = {}

    @staticmethod
    def _derive(key: str, salt: bytes) -> bytes:
        return hashlib.scrypt(
            key.encode("ascii"), salt=salt, n=SCRYPT_N,
            r=SCRYPT_R, p=SCRYPT_P, dklen=SCRYPT_LENGTH,
        )

    def _load_verifier(self) -> tuple[bytes, bytes]:
        if self.key_file.is_symlink():
            raise RecoveryUnauthorized("Clé de récupération indisponible.")
        try:
            data = json.loads(self.key_file.read_text(encoding="utf-8"))
            if not isinstance(data, dict) or data.get("version") != 1:
                raise ValueError("invalid verifier")
            salt = bytes.fromhex(data["salt"])
            digest = bytes.fromhex(data["digest"])
            if len(salt) != 16 or len(digest) != SCRYPT_LENGTH:
                raise ValueError("invalid verifier")
            return salt, digest
        except (OSError, ValueError, KeyError, TypeError, json.JSONDecodeError) as exc:
            raise RecoveryUnauthorized("Clé de récupération indisponible.") from exc

    def create_or_rotate_key(self) -> str:
        """Persist a new verifier atomically and invalidate all active sessions."""
        key = secrets.token_urlsafe(32)
        salt = secrets.token_bytes(16)
        digest = self._derive(key, salt)
        payload = json.dumps(
            {"version": 1, "salt": salt.hex(), "digest": digest.hex()},
            separators=(",", ":"),
        ) + "\n"
        with self._lock:
            parent = self.key_file.parent
            parent.mkdir(mode=0o700, parents=True, exist_ok=True)
            if parent.is_symlink() or self.key_file.is_symlink():
                raise OSError("Le stockage de la clé de récupération est invalide.")
            parent.chmod(0o700)
            fd, temporary_name = tempfile.mkstemp(prefix=".recovery-key-", dir=str(parent))
            try:
                os.fchmod(fd, 0o600)
                with os.fdopen(fd, "w", encoding="utf-8") as handle:
                    handle.write(payload)
                    handle.flush()
                    os.fsync(handle.fileno())
                os.replace(temporary_name, self.key_file)
                os.chmod(self.key_file, 0o600)
            finally:
                try:
                    os.unlink(temporary_name)
                except FileNotFoundError:
                    pass
            self._sessions.clear()
            self._failures.clear()
        return key

    def issue_session(self, key: str, client_id: str) -> str:
        """Validate a recovery key and return an in-memory, short-lived token."""
        with self._lock:
            self._check_rate_limit(client_id)
            if not isinstance(key, str) or not KEY_PATTERN.fullmatch(key):
                self._record_failure(client_id)
                raise RecoveryUnauthorized("Clé de récupération absente ou invalide.")
            try:
                salt, expected = self._load_verifier()
                actual = self._derive(key, salt)
                valid = hmac.compare_digest(actual, expected)
            except RecoveryUnauthorized:
                valid = False
            if not valid:
                self._record_failure(client_id)
                raise RecoveryUnauthorized("Clé de récupération absente ou invalide.")
            token = secrets.token_urlsafe(32)
            token_digest = hashlib.sha256(token.encode("ascii")).hexdigest()
            self._failures.pop(client_id, None)
            self._purge_expired_sessions()
            self._sessions[token_digest] = self.clock() + self.session_ttl
            return token

    def _check_rate_limit(self, client_id: str) -> None:
        now = self.clock()
        recent = [stamp for stamp in self._failures.get(client_id, []) if now - stamp < self.rate_window]
        self._failures[client_id] = recent
        if len(recent) >= self.max_failed_attempts:
            raise RecoveryRateLimited("Trop de tentatives. Réessaie plus tard.")

    def _record_failure(self, client_id: str) -> None:
        with self._lock:
            self._check_rate_limit(client_id)
            self._failures.setdefault(client_id, []).append(self.clock())

    def _purge_expired_sessions(self) -> None:
        now = self.clock()
        self._sessions = {token: expiry for token, expiry in self._sessions.items() if expiry > now}

    def is_session_valid(self, token: str) -> bool:
        if not isinstance(token, str) or not token:
            return False
        digest = hashlib.sha256(token.encode("utf-8")).hexdigest()
        with self._lock:
            self._purge_expired_sessions()
            expiry = self._sessions.get(digest)
            return expiry is not None and expiry > self.clock()

    def revoke_sessions(self) -> None:
        with self._lock:
            self._sessions.clear()
